import torch
import torch.nn as nn
import torch.optim as optim
from torch.optim.lr_scheduler import CosineAnnealingLR
import numpy as np
import os
from torch.utils.data import Dataset, DataLoader

# 1. Dataset Loader
class CUBFeatureDataset(Dataset):
    def __init__(self, split="train"):
        base_dir = "data/features"
        self.features = np.load(os.path.join(base_dir, f"features_{split}.npy"))
        self.labels = np.load(os.path.join(base_dir, f"labels_{split}.npy"))
        self.concepts = np.load(os.path.join(base_dir, f"concepts_{split}.npy"))
        
    def __len__(self):
        return len(self.labels)
        
    def __getitem__(self, idx):
        x = torch.FloatTensor(self.features[idx])
        c = torch.FloatTensor(self.concepts[idx])
        y = torch.tensor(self.labels[idx], dtype=torch.long)
        return x, c, y

# 2. Architecture
class BaselineCBM(nn.Module):
    def __init__(self, input_dim=512, num_concepts=312, num_classes=200):
        super().__init__()
        self.concept_predictor = nn.Linear(input_dim, num_concepts)
        self.label_predictor = nn.Linear(num_concepts, num_classes)
        
    def forward(self, x):
        concept_logits = self.concept_predictor(x)
        concept_probs = torch.sigmoid(concept_logits)
        class_logits = self.label_predictor(concept_probs)
        return concept_logits, class_logits

# 3. The Sequential Training Strategy
def train_sequential():
    train_loader = DataLoader(CUBFeatureDataset("train"), batch_size=64, shuffle=True)
    model = BaselineCBM()
    
    # --- PHASE 1: The Ornithology Class (Train Concepts Only) ---
    print("--- PHASE 1: Training Concept Predictor ---")
    # Optimizer ONLY touches the concept layer
    optimizer_c = optim.Adam(model.concept_predictor.parameters(), lr=0.01)
    scheduler_c = CosineAnnealingLR(optimizer_c, T_max=30)
    criterion_c = nn.BCEWithLogitsLoss()
    
    for epoch in range(30):
        model.train()
        total_loss = 0
        for x, c_true, _ in train_loader:
            optimizer_c.zero_grad()
            c_logits = model.concept_predictor(x)
            loss = criterion_c(c_logits, c_true)
            loss.backward()
            optimizer_c.step()
            total_loss = total_loss + loss.item()
        
        scheduler_c.step() # Smoothly reduce learning rate
        if (epoch + 1) % 5 == 0:
            print(f"Phase 1 - Epoch {epoch+1}/30 | Concept Loss: {total_loss/len(train_loader):.4f}")

    # --- PHASE 2: The Taxonomy Class (Train Labels Only) ---
    print("\n--- PHASE 2: Training Label Predictor ---")
    # Freeze the concept layer completely to prevent "concept leakage"
    for param in model.concept_predictor.parameters():
        param.requires_grad = False
        
    # Optimizer ONLY touches the label layer
    optimizer_y = optim.Adam(model.label_predictor.parameters(), lr=0.01)
    scheduler_y = CosineAnnealingLR(optimizer_y, T_max=30)
    criterion_y = nn.CrossEntropyLoss()
    
    for epoch in range(30):
        model.train()
        total_loss, correct_preds = 0, 0
        for x, _, y_true in train_loader:
            optimizer_y.zero_grad()
            # Forward pass: concepts are generated by the frozen layer
            _, class_logits = model(x)
            loss = criterion_y(class_logits, y_true)
            loss.backward()
            optimizer_y.step()
            
            total_loss = total_loss + loss.item()
            correct_preds = correct_preds + (class_logits.argmax(dim=1) == y_true).sum().item()
            
        scheduler_y.step()
        acc = correct_preds / len(train_loader.dataset)
        if (epoch + 1) % 5 == 0:
            print(f"Phase 2 - Epoch {epoch+1}/30 | Label Loss: {total_loss/len(train_loader):.4f} | Train Acc: {acc*100:.2f}%")
            
    # Save the strictly bottlenecked model
    torch.save(model.state_dict(), "vlg_cbm_sequential.pth")
    print("\nModel saved as vlg_cbm_sequential.pth")

if __name__ == "__main__":
    train_sequential()